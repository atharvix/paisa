package com.antiscam.ticketing.service;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.UUID;

@Service
public class RazorpayRouteService {

    private static final Logger log = LoggerFactory.getLogger(RazorpayRouteService.class);

    @Value("${app.razorpay.key-id:rzp_test_antiscam_key_id}")
    private String keyId;

    @Value("${app.razorpay.key-secret:rzp_test_antiscam_secret_val}")
    private String keySecret;

    @Value("${app.razorpay.webhook-secret:rzp_webhook_secret_signature_test}")
    private String webhookSecret;

    @Value("${app.razorpay.simulation-mode:true}")
    private boolean simulationMode;

    /**
     * Creates a Linked Account for the event host via Razorpay Route API.
     * In simulation mode or local dev, generates a realistic `acc_...` identifier.
     */
    public String createLinkedAccount(String businessName, String pan, String bankAccount, String ifsc) {
        log.info("Creating Razorpay Route Linked Account for: {} (PAN: {})", businessName, pan);
        if (simulationMode) {
            String sanitized = businessName.replaceAll("[^a-zA-Z0-9]", "").toLowerCase();
            if (sanitized.length() > 8) sanitized = sanitized.substring(0, 8);
            return "acc_" + sanitized + "_" + UUID.randomUUID().toString().substring(0, 8);
        }
        // In live production, execute HTTP POST to https://api.razorpay.com/v1/accounts
        return "acc_live_" + UUID.randomUUID().toString().substring(0, 10);
    }

    /**
     * Initiates an order with Razorpay Route split payment payload.
     * Holds ticket payout in escrow until specified release timestamp.
     */
    public String createSplitHoldOrder(BigDecimal grossAmount,
                                      BigDecimal netPayoutAmount,
                                      String hostAccountId,
                                      long onHoldUntilEpochSeconds,
                                      String receiptId) {

        log.info("Creating Razorpay Route Split Order: Gross={}, Host={}, NetPayout={}, HoldUntil={}",
                grossAmount, hostAccountId, netPayoutAmount, onHoldUntilEpochSeconds);

        if (simulationMode) {
            return "order_sim_" + UUID.randomUUID().toString().replace("-", "").substring(0, 14);
        }
        // In live production, execute HTTP POST to https://api.razorpay.com/v1/orders with transfers payload
        return "order_live_" + UUID.randomUUID().toString().replace("-", "").substring(0, 14);
    }

    /**
     * Verifies payment signature generated by Razorpay Checkout SDK.
     * signature = HMAC-SHA256(order_id + "|" + payment_id, secret)
     */
    public boolean verifyPaymentSignature(String orderId, String paymentId, String providedSignature) {
        if (simulationMode) {
            return true; // Auto-verify in simulation test mode
        }
        try {
            String data = orderId + "|" + paymentId;
            String computedSignature = hmacSha256(data, keySecret);
            return MessageDigest.isEqual(computedSignature.getBytes(StandardCharsets.UTF_8),
                    providedSignature.getBytes(StandardCharsets.UTF_8));
        } catch (Exception e) {
            log.error("Payment signature verification failed: {}", e.getMessage());
            return false;
        }
    }

    /**
     * Verifies Webhook HMAC-SHA256 signature from X-Razorpay-Signature header.
     */
    public boolean verifyWebhookSignature(String payload, String signatureHeader) {
        try {
            String computed = hmacSha256(payload, webhookSecret);
            return MessageDigest.isEqual(computed.getBytes(StandardCharsets.UTF_8),
                    signatureHeader.getBytes(StandardCharsets.UTF_8));
        } catch (Exception e) {
            log.error("Webhook signature verification failed: {}", e.getMessage());
            return false;
        }
    }

    public String getKeyId() {
        return keyId;
    }

    private String hmacSha256(String data, String secret) throws Exception {
        Mac mac = Mac.getInstance("HmacSHA256");
        SecretKeySpec secretKey = new SecretKeySpec(secret.getBytes(StandardCharsets.UTF_8), "HmacSHA256");
        mac.init(secretKey);
        byte[] hash = mac.doFinal(data.getBytes(StandardCharsets.UTF_8));
        return HexFormat.of().formatHex(hash);
    }
}
